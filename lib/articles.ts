/**
 * Long-form explainer articles for /articles. Written for this site (not translated or copied),
 * each with sources a reader can check.
 */
export interface ArticleSection {
  heading: string;
  paragraphs: string[];
  /**
   * Points scientists still disagree on, or where evidence is thin, explained so readers don't
   * take them as settled. Shown in a separate "still debated" box under the section.
   */
  debated?: string[];
}

export interface ArticleBody {
  title: string;
  summary: string;
  /** Short label for the list card, e.g. "การเกิดฟอสซิล". */
  topic: string;
  /** Boxed note under the summary saying where the article's facts come from, for touchier topics. */
  disclaimer?: string;
  sections: ArticleSection[];
}

/** Thai is the source text; English lives in lib/articles-en.ts. */
export interface Article extends ArticleBody {
  slug: string;
  sources: { label: string; url: string }[];
  /**
   * Which sources back which text, shown as [n] markers. Keys are "section.paragraph", or
   * "section.dN" for the Nth "still debated" point (all 0-based); values are 1-based positions in
   * `sources`. Kept here rather than in the section text so both languages share one mapping.
   */
  citations?: Record<string, number[]>;
}

